"""
LLM-as-a-Judge Evaluator for Avalon.
Uses Gemini (or any OpenAI-compatible API) to score agent performance 
on Strategy, Hallucination, and Linguistic Diversity based on the DeepEval rubric.
"""

import os
import json
import argparse
from pathlib import Path
from tqdm import tqdm
from openai import OpenAI

JUDGE_SYSTEM_PROMPT = """You are a professional content quality evaluator, and you also understand the rules of the game The Resistance: Avalon. 
The following will provide you with dialogue and history, which is generated by a language model imagining itself playing the game Avalon. 
You need to evaluate the quality of Dialogue History based on the three criteria below. 
For each criterion, you must assign a score from 0 to 100 independently, and also provide your reasoning.

1. Strategy Score (0-100):
- 0–25: Severely lacks strategic value, hinders faction's objective.
- 26–50: Low strategic value, neither advancing nor clearly hindering.
- 51–75: Shows some strategic intent, slightly advancing faction's objective.
- 76–100: Highly strategic, significantly advancing faction's objective.

2. Hallucination Score (0-100, LOWER is better):
- 0–25: No or almost no hallucinations; completely faithful to game history facts.
- 26–50: Minor factual errors that do not match history.
- 51–75: Noticeable factual errors not aligned with history.
- 76–100: Severe hallucinations; most content contradicts game history.

3. Diversity Score (0-100):
- 0–25: Extremely formulaic, robotic sentence repetition.
- 26–50: Minor variations but predictable rigid templates.
- 51–75: Natural language variation, avoids repetitive openers.
- 76–100: High linguistic and strategic distinctiveness, human-like and dynamic.

Output Format: Must be valid JSON with the exact following schema:
{
  "strategy": {"score": <int 0-100>, "reason": "<explanation>"},
  "hallucination": {"score": <int 0-100>, "reason": "<explanation>"},
  "diversity": {"score": <int 0-100>, "reason": "<explanation>"}
}
"""


def parse_args():
    parser = argparse.ArgumentParser(description="Evaluate Avalon test outputs using LLM Judge")
    parser.add_argument("--input_folder", type=str, default="eval_results/sft", 
                        help="Folder containing result_converted_*.json files")
    parser.add_argument("--api_key", type=str, default=os.getenv("GEMINI_API_KEY", ""),
                        help="Gemini API Key (or set GEMINI_API_KEY env variable)")
    parser.add_argument("--model", type=str, default="gemini-2.5-flash",
                        help="Judge model name")
    return parser.parse_args()


def evaluate_batch(input_folder, api_key, model_name):
    # Gemini API 支援 OpenAI 相容 endpoint
    client = OpenAI(
        api_key=api_key,
        base_url="https://generativelanguage.googleapis.com/v1beta/openai/"
    )

    folder = Path(input_folder)
    result_files = sorted(list(folder.glob("result_converted_*.json")))

    if not result_files:
        print(f"❌ 在 {folder} 中找不到任何 result_converted_*.json 檔案！")
        return

    print(f">>> 找到 {len(result_files)} 個測試檔案，開始評分...")

    for file_path in result_files:
        score_filename = file_path.name.replace("result_", "score_")
        output_score_path = folder / score_filename

        # 若已評分過則跳過
        if output_score_path.exists():
            print(f"⏭️ {score_filename} 已存在，跳過。")
            continue

        print(f" 正在評估: {file_path.name} -> {score_filename}")
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        evaluation_results = []
        for idx, item in enumerate(tqdm(data, desc=file_path.name)):
            prompt = item.get("prompt", "")
            completion = item.get("completion", "")

            user_eval_content = f"--- GAME STATE PROMPT ---\n{prompt}\n\n--- MODEL COMPLETION ---\n{completion}"

            try:
                response = client.chat.completions.create(
                    model=model_name,
                    messages=[
                        {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
                        {"role": "user", "content": user_eval_content}
                    ],
                    response_format={"type": "json_object"},
                    temperature=0.2
                )
                eval_json = json.loads(response.choices[0].message.content)
                eval_json["index"] = idx + 1
                evaluation_results.append(eval_json)
            except Exception as e:
                print(f"⚠️ 評估第 {idx+1} 筆失敗: {e}")

        # 儲存評分結果
        with open(output_score_path, "w", encoding="utf-8") as f_out:
            json.dump({"evaluation": evaluation_results}, f_out, indent=2, ensure_ascii=False)
        print(f"✅ 成功儲存成績單: {output_score_path}")


if __name__ == "__main__":
    args = parse_args()
    if not args.api_key:
        print("⚠️ 請提供 --api_key 或設定環境變數 GEMINI_API_KEY")
    else:
        evaluate_batch(args.input_folder, args.api_key, args.model)